// In-memory lookups
const COUNTRY_MAP_BY_CODE = new Map<string, CountryReference>();
const COUNTRY_MAP_BY_ALPHA3 = new Map<string, CountryReference>();
const COUNTRY_MAP_BY_NAME = new Map<string, CountryReference>();

for (const country of COUNTRIES_DATA) {
  COUNTRY_MAP_BY_CODE.set(country.code.toUpperCase(), country);
  COUNTRY_MAP_BY_ALPHA3.set(country.alpha3.toUpperCase(), country);
  COUNTRY_MAP_BY_NAME.set(country.name.toLowerCase(), country);
  if (country.officialName) {
    COUNTRY_MAP_BY_NAME.set(country.officialName.toLowerCase(), country);
  }
}

export function getAllCountries(): CountryReference[] {
  return COUNTRIES_DATA;
}

export function getCountryByCode(codeOrAlpha3: string): CountryReference | undefined {
  if (!codeOrAlpha3) return undefined;
  const upper = codeOrAlpha3.toUpperCase().trim();
  if (upper.length === 2) {
    return COUNTRY_MAP_BY_CODE.get(upper);
  }
  if (upper.length === 3) {
    return COUNTRY_MAP_BY_ALPHA3.get(upper);
  }
  return COUNTRY_MAP_BY_NAME.get(codeOrAlpha3.toLowerCase().trim());
}

export function getSovereignStatesCount(): number {
  return COUNTRIES_DATA.filter((c) => c.isSovereignState).length;
}

export function searchCountries(query: string): CountryReference[] {
  if (!query || !query.trim()) return COUNTRIES_DATA;
  const q = query.toLowerCase().trim();
  return COUNTRIES_DATA.filter(
    (c) =>
      c.code.toLowerCase().includes(q) ||
      c.alpha3.toLowerCase().includes(q) ||
      c.name.toLowerCase().includes(q) ||
      c.officialName.toLowerCase().includes(q) ||
      (c.nativeName && c.nativeName.toLowerCase().includes(q)) ||
      c.callingCode.includes(q) ||
      c.currency.toLowerCase().includes(q)
  );
}
