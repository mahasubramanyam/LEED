  'NO', 'GB', 'AU', 'US', 'FR', 'SG', 'JP',
  'FI', 'PL', 'NL', 'NZ', 'CH', 'IE',
  'CA', 'DE', 'IN', 'SE', 'DK', 'KR', 'SA',
